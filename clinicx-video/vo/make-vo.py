# Voice-over for the dubbed version: one clip per line of vo/script.json, with word timings.
# Run with the project's venv:  .venv/bin/python vo/make-vo.py
# Writes vo/<name>.mp3 and vo/words.json ({name: [[start, end, word], ...]} in seconds from the clip's start).
import asyncio, json, pathlib
import edge_tts

HERE = pathlib.Path(__file__).parent
cfg = json.loads((HERE / 'script.json').read_text(encoding='utf-8'))


async def one(name, text):
    com = edge_tts.Communicate(text, cfg['voice'], rate=cfg['rate'], pitch=cfg['pitch'], boundary='WordBoundary')
    words = []
    with open(HERE / f'{name}.mp3', 'wb') as f:
        async for chunk in com.stream():
            if chunk['type'] == 'audio':
                f.write(chunk['data'])
            elif chunk['type'] == 'WordBoundary':
                s = chunk['offset'] / 1e7
                words.append([round(s, 3), round(s + chunk['duration'] / 1e7, 3), chunk['text']])
    return name, words


async def main():
    out = {}
    for name, text in cfg['lines']:
        n, w = await one(name, text)
        out[n] = w
        print(f'{n}: {len(w)} words, last ends {w[-1][1] if w else 0:.2f}s')
    (HERE / 'words.json').write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding='utf-8')
    # the same table as an ES module: js/timeline.mjs imports it in the browser and in Node
    (HERE.parent / 'js' / 'vo.data.mjs').write_text('// generated by vo/make-vo.py — word timings of each voice-over clip, seconds from the clip start\nexport const VO_WORDS = '
        + json.dumps(out, ensure_ascii=False) + ';\n', encoding='utf-8')

asyncio.run(main())
